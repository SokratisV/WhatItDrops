"""WhatItDrops Classic data generator (DEV ONLY).

Source: the CMaNGOS TBC world database (GPL-3.0), https://github.com/cmangos/tbc-db
  Full_DB/TBCDB_*.sql.gz  ->  decompress to tools/cmangos/tbcdb.sql

Everything the Classic clients ship is derived from that one dump:
  * loot percentages: the server's loot templates resolved into plain chances (cmangos_loot.py)
  * item names and quality, creature names
  * which creatures live where, so the data can be split into per-region packs
  * the dungeon boss list and the quest-item flags

Writes, under <AddOns dir>:
  WhatItDrops_<Pack>/WhatItDrops_<Pack>.lua   (the five regional packs; their TOCs are not touched)
  WhatItDrops/Data/WhatItDropsItems.lua       (names + quality)
  WhatItDrops/Data/WhatItDropsBosses.lua
  WhatItDrops/Data/WhatItDropsQuestItems.lua

Run:  python generate-from-cmangos.py <tbcdb.sql> <AddOns dir>
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import cmangos_loot  # noqa: E402
import tdbparse as t  # noqa: E402

PACKS = ["EasternKingdoms", "Kalimdor", "Outland", "Instances", "Misc"]
CONTINENTS = {0: "EasternKingdoms", 1: "Kalimdor", 530: "Outland"}
MAX_SPECIFIC = 500       # past this a table is a corrupted reference dump, not loot (cf. the Don Carlos bug)
WORLD_MIN_PCT = 0.1      # world-drop pools list hundreds of items at fractions of a percent; keep the real ones
WORLD_MAX_ROWS = 80
QUEST_CLASS = 12


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ").strip() + '"'


def fmt(p):
    return "%g" % round(p, 2)


def pack_of(map_id):
    return CONTINENTS.get(map_id, "Instances")


def main(sql, addons):
    print("Parsing spawns ...")
    guid_map = {}
    spawn_maps = collections.defaultdict(collections.Counter)       # entry -> {map: count}
    for r in t.rows(sql, "creature", ["guid", "id", "map"]):
        if r["id"]:
            spawn_maps[r["id"]][r["map"]] += 1
        else:
            guid_map[r["guid"]] = r["map"]
    # newer dumps leave creature.id at 0 for spawns whose creatures are listed in creature_spawn_entry
    for r in t.rows(sql, "creature_spawn_entry", ["guid", "entry"]):
        if r["guid"] in guid_map:
            spawn_maps[r["entry"]][guid_map[r["guid"]]] += 1

    print("Parsing templates ...")
    tmpl = {r["Entry"]: r for r in t.rows(sql, "creature_template", ["Entry", "Name", "LootId", "HeroicEntry", "Rank"])}
    heroic_of = {r["HeroicEntry"]: e for e, r in tmpl.items() if r["HeroicEntry"]}
    items = {r["entry"]: r for r in t.rows(sql, "item_template", ["entry", "name", "Quality", "class"])}

    print("Resolving loot ...")
    loot = cmangos_loot.Loot(sql)
    per_loot = {}
    npc_rows = {}
    skipped = []
    for entry, r in sorted(tmpl.items()):
        lid = r["LootId"]
        if not lid:
            continue
        if lid not in per_loot:
            spec, world = loot.for_loot_id(lid)
            spec = {i: p for i, p in spec.items() if i in items and round(p, 2) > 0}
            world = {i: p for i, p in world.items() if i in items and p >= WORLD_MIN_PCT}
            world = dict(sorted(world.items(), key=lambda kv: -kv[1])[:WORLD_MAX_ROWS])
            per_loot[lid] = (spec, world)
        spec, world = per_loot[lid]
        if not spec and not world:
            continue
        if len(spec) > MAX_SPECIFIC:
            skipped.append((entry, r["Name"], len(spec)))
            continue
        npc_rows[entry] = (spec, world)
    for entry, name, n in skipped:
        print("WARNING: skipping npc %d (%s): %d mob-specific drops looks like a corrupted reference dump" % (entry, name, n))

    print("Writing packs ...")
    buf = {p: [] for p in PACKS}
    item_ids = set()
    for entry in sorted(npc_rows):
        spec, world = npc_rows[entry]
        s = sorted(spec.items(), key=lambda kv: -kv[1])
        w = sorted(world.items(), key=lambda kv: -kv[1])
        flat = [str(len(s))]
        for i, p in s + w:
            flat.append("%d,%s" % (i, fmt(p)))
            item_ids.add(i)
        line = "d[%d]={%s}" % (entry, ",".join(flat))
        maps = spawn_maps.get(entry) or spawn_maps.get(heroic_of.get(entry), None)
        parts = sorted({pack_of(m) for m in maps}) if maps else ["Misc"]
        for p in parts:
            buf[p].append(line)
    for p in PACKS:
        d = os.path.join(addons, "WhatItDrops_" + p)
        os.makedirs(d, exist_ok=True)
        head = ("-- AUTO-GENERATED by tools/generate-from-cmangos.py -- do not edit.\n"
                "-- Partition: %s. Loot percentages resolved from the CMaNGOS tbc-db (GPL v3).\n"
                "-- Flat: d[npc]={specificCount,item,pct,...}; the rows past specificCount are world drops.\n"
                "WhatItDropsFull = WhatItDropsFull or {}\nlocal d = WhatItDropsFull\n\n") % p
        with open(os.path.join(d, "WhatItDrops_%s.lua" % p), "w", encoding="utf-8", newline="\n") as f:
            f.write(head + "\n".join(buf[p]) + "\n")
        print("  WhatItDrops_%-16s %5d npcs" % (p, len(buf[p])))

    print("Writing names ...")
    data = os.path.join(addons, "WhatItDrops", "Data")
    out = [
        "-- AUTO-GENERATED by tools/generate-from-cmangos.py -- do not edit.",
        "-- Item names+quality and creature names from the CMaNGOS tbc-db (GPL v3).",
        "-- Retail has its own data (WhatItDrops_Retail); these tables are Classic-only.",
        "if WOW_PROJECT_ID ~= nil and WOW_PROJECT_ID == WOW_PROJECT_MAINLINE then return end",
        "WhatItDropsItemName = {",
    ]
    out += ["[%d]=%s," % (i, lua_str(items[i]["name"])) for i in sorted(item_ids)]
    out += ["}", "WhatItDropsItemQuality = {"]
    out += ["[%d]=%d," % (i, items[i]["Quality"]) for i in sorted(item_ids)]
    out += ["}", "WhatItDropsNpcName = {"]
    out += ["[%d]=%s," % (e, lua_str(tmpl[e]["Name"])) for e in sorted(npc_rows) if tmpl[e]["Name"]]
    out += ["}"]
    with open(os.path.join(data, "WhatItDropsItems.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("  %d items, %d npcs" % (len(item_ids), len(npc_rows)))

    print("Writing bosses ...")
    by_map = collections.defaultdict(set)
    for entry, maps in spawn_maps.items():
        if entry not in npc_rows:
            continue
        spec = npc_rows[entry][0]
        best = max((items[i]["Quality"] for i in spec), default=0)
        for m, n in maps.items():
            if m in CONTINENTS:
                continue
            if (n == 1 and best >= 3) or tmpl[entry]["Rank"] == 3:
                by_map[m].add(entry)
    out = [
        "-- AUTO-GENERATED by tools/generate-from-cmangos.py -- do not edit.",
        "-- Instance map id -> boss NPC ids. Heuristic: single-spawn rare+ dropper, or Rank 3.",
        "-- Retail has its own data (WhatItDrops_Retail); these tables are Classic-only.",
        "if WOW_PROJECT_ID ~= nil and WOW_PROJECT_ID == WOW_PROJECT_MAINLINE then return end",
        "WhatItDropsInstanceBoss = {",
    ]
    bosses = 0
    for m in sorted(by_map):
        ids = sorted(by_map[m])
        bosses += len(ids)
        out.append("[%d]={%s}," % (m, ",".join(map(str, ids))))
    out.append("}")
    with open(os.path.join(data, "WhatItDropsBosses.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("  %d instance maps, %d bosses" % (len(by_map), bosses))

    print("Writing quest items ...")
    quest = sorted(i for i in item_ids if items[i]["class"] == QUEST_CLASS)
    out = [
        "-- AUTO-GENERATED by tools/generate-from-cmangos.py -- do not edit.",
        "-- Item ids that are Quest-class (item_template.class==12). Used to flag quest drops.",
        "-- Retail has its own data (WhatItDrops_Retail); these tables are Classic-only.",
        "if WOW_PROJECT_ID ~= nil and WOW_PROJECT_ID == WOW_PROJECT_MAINLINE then return end",
        "WhatItDropsQuestItem = {",
    ] + ["[%d]=1," % i for i in quest] + ["}"]
    with open(os.path.join(data, "WhatItDropsQuestItems.lua"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("  %d quest items" % len(quest))
    print("Done.")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
